-- Persistent cashier login throttling. No PIN or password is stored.
CREATE TABLE IF NOT EXISTS public.cashier_login_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash text NOT NULL,
  tenant_slug text NOT NULL,
  branch_slug text NOT NULL,
  username text NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS cashier_login_attempts_lookup_idx
  ON public.cashier_login_attempts (attempted_at DESC, ip_hash, tenant_slug, branch_slug, username);
ALTER TABLE public.cashier_login_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cashier_login_attempts FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.check_cashier_login_rate_limit(
  p_ip text,
  p_tenant_slug text,
  p_branch_slug text,
  p_username text,
  p_record_failure boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_catalog
AS $$
DECLARE
  v_ip_hash text := encode(extensions.digest(coalesce(nullif(trim(p_ip), ''), 'unknown'), 'sha256'), 'hex');
  v_tenant text := lower(btrim(coalesce(p_tenant_slug, '')));
  v_branch text := lower(btrim(coalesce(p_branch_slug, '')));
  v_username text := lower(btrim(coalesce(p_username, '')));
  v_now timestamptz := now();
  v_ip_count integer;
  v_tenant_count integer;
  v_branch_count integer;
  v_user_count integer;
  v_count integer;
  v_retry integer := 0;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(v_ip_hash || '|' || v_tenant || '|' || v_branch || '|' || v_username, 0));
  IF p_record_failure THEN
    INSERT INTO public.cashier_login_attempts (ip_hash, tenant_slug, branch_slug, username)
    VALUES (v_ip_hash, v_tenant, v_branch, v_username);
  END IF;
  DELETE FROM public.cashier_login_attempts WHERE attempted_at < v_now - interval '2 hours';
  SELECT count(*)::integer INTO v_ip_count FROM public.cashier_login_attempts WHERE ip_hash = v_ip_hash AND attempted_at >= v_now - interval '15 minutes';
  SELECT count(*)::integer INTO v_tenant_count FROM public.cashier_login_attempts WHERE tenant_slug = v_tenant AND attempted_at >= v_now - interval '15 minutes';
  SELECT count(*)::integer INTO v_branch_count FROM public.cashier_login_attempts WHERE tenant_slug = v_tenant AND branch_slug = v_branch AND attempted_at >= v_now - interval '15 minutes';
  SELECT count(*)::integer INTO v_user_count FROM public.cashier_login_attempts WHERE tenant_slug = v_tenant AND branch_slug = v_branch AND username = v_username AND attempted_at >= v_now - interval '15 minutes';
  v_count := GREATEST(v_ip_count, v_tenant_count, v_branch_count, v_user_count);
  IF v_count >= 10 THEN v_retry := 3600;
  ELSIF v_count >= 5 THEN v_retry := 300;
  END IF;
  RETURN jsonb_build_object('allowed', v_retry = 0, 'retry_after_seconds', v_retry);
END;
$$;
REVOKE ALL ON FUNCTION public.check_cashier_login_rate_limit(text, text, text, text, boolean) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.check_cashier_login_rate_limit(text, text, text, text, boolean) TO service_role;
